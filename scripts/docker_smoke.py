"""Check the built Compose stack without external provider calls or dependencies."""
import argparse
import json
import re
from pathlib import Path
from urllib.error import HTTPError
from urllib.request import Request, urlopen


def check(base_url, password=None):
    def request(path, method='GET', credential=None):
        headers = {'Authorization': 'Bearer ' + credential} if credential else {}
        return urlopen(Request(base_url.rstrip('/') + path, headers=headers, method=method), timeout=20)

    def get(path):
        with request(path, credential=password) as response:
            assert response.status == 200, (path, response.status)
            return response.read().decode(), response.headers

    html, headers = get('/')
    assert 'Waywise' in html and 'text/html' in headers.get('Content-Type', ''), 'Frontend did not serve the built app'
    asset = re.search(r'src="(/assets/[^\"]+\.js)"', html)
    assert asset, 'Built JavaScript asset is missing from the page'
    javascript, headers = get(asset.group(1))
    assert javascript and 'javascript' in headers.get('Content-Type', ''), 'JavaScript asset is not served correctly'
    assert 'immutable' in ', '.join(headers.get_all('Cache-Control', [])), 'Built assets should be immutable'
    health, _ = get('/healthz')
    assert health.strip() == 'ok', 'Nginx readiness failed'
    health, _ = get('/api/health')
    assert json.loads(health) == {'status': 'ok'}, 'Django readiness through Nginx failed'
    metadata, _ = get('/api/access')
    required = json.loads(metadata)['password_required']
    if required:
        assert password, 'Supply --password-file for this protected demo'
        for path, method in [('/api/access', 'POST'), ('/api/example', 'GET'),
                             ('/api/places?q=Denver', 'GET'), ('/api/plan', 'POST')]:
            for credential in (None, 'wrong-smoke-test-password'):
                try:
                    with request(path, method, credential):
                        raise AssertionError('Unauthenticated API request was allowed: ' + path)
                except HTTPError as error:
                    assert error.code == 401, (path, error.code)
                    assert error.headers['Cache-Control'] == 'no-store'
        with request('/api/access', 'POST', password) as response:
            assert response.status == 200
    body, _ = get('/api/example?load_lb=20000&spacing_miles=25')
    plan = json.loads(body)
    assert plan['mode'] == 'example' and plan['forecast_hours'] == 48, 'Example forecast contract failed'
    assert len(plan['routes']) == 3, 'Recorded example routes are missing'
    for route in plan['routes']:
        assert len(route['geometry']['coordinates']) >= 2 and len(route['checkpoints']) >= 2
        assert route['checkpoints'][0]['mile'] == 0
        assert route['checkpoints'][-1]['mile'] > 0
    assert plan['heatmap'] and all(len(point['scores']) == 49 for point in plan['heatmap'])
    print('Container smoke checks passed: frontend, JavaScript, Nginx readiness, Django proxy and complete example forecast and reviewer access checks.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base-url', default='http://127.0.0.1:8080')
    parser.add_argument('--password-file', help='Private JSON file generated by create_demo_password.py')
    args = parser.parse_args()
    password = json.loads(Path(args.password_file).read_text())['password'] if args.password_file else None
    check(args.base_url, password)
